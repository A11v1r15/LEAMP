<h2>Como usar o sistema</h2>

<h3>Leitura e busca</h3>

<p>
	&emsp;Use a página de livros para procurar obras disponíveis. Obras "Pendente"
	estão em processo de catalogação e serão disponibilizadas depois.
</p>

<h3>Login</h3>

<p>
	&emsp;O cadastro e login são realizados usando
	contas Google "@gmail.com" e institucionais
	do IFCE "@ifce.edu.br" ou "@aluno.ifce.edu.br".
	Caso você seja aluno, é importante que se cadastre
	com seu e-mail institucional.
</p>
<p>
	&emsp;Se tiver problemas em acessar sua conta instituconal, entre em contato pelo e-mail
	<a href="mailto:cti.camocim@ifce.edu.br?subject=Ler é a minha praia">cti.camocim@ifce.edu.br</a>
	ou presencialmente no setor de CTI no campus.
</p>

<h3>Empréstimos</h3>

<p>
	&emsp;Os empréstimos são registrados
	pela equipe responsável, retire os livros
	na sala do ensino, ao lado da biblioteca.
	Para fazer empréstimos, é necessário
	estar cadastrado no sistema.
</p>

<h3>Resenhas</h3>

<p>
	&emsp;Para fazer resenhas das obras, acesse seu perfil e clique no botão "Escrever Resenha"
	no card de emréstimo relacionado. As resenhas podem ser editadas posteriormente, caso necessário.
	As resenhas serão públicas quando aprovadas e a aprovação é manual, por favor espere.
	Mantenha respeito e bom senso.
</p>

<h3>Responsabilidade</h3>

<p>
	&emsp;O usuário é responsável pelos
	livros emprestados em seu nome.
</p>
